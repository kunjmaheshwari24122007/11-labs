def load_env_keys():
    """Load API keys from .env file or environment variables."""
    keys = {
        "ELEVENLABS_API_KEY": os.environ.get("ELEVENLABS_API_KEY", ""),
        "DID_API_KEY": os.environ.get("DID_API_KEY", "")
    }
    env_file = os.path.join(BASE_DIR, ".env")
    if os.path.isfile(env_file):
        with open(env_file, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("#") or not line:
                    continue
                if line.startswith("ELEVENLABS_API_KEY="):
                    keys["ELEVENLABS_API_KEY"] = line.split("=", 1)[1].strip()
                elif line.startswith("DID_API_KEY="):
                    keys["DID_API_KEY"] = line.split("=", 1)[1].strip()
    return keys

def save_env_key(key_name, key_value):
    """Safely update or add an API key in the .env file."""
    env_file = os.path.join(BASE_DIR, ".env")
    lines = []
    found = False
    if os.path.isfile(env_file):
        with open(env_file, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip().startswith(f"{key_name}="):
                    lines.append(f"{key_name}={key_value}\n")
                    found = True
                else:
                    lines.append(line)
    if not found:
        lines.append(f"\n{key_name}={key_value}\n")
    with open(env_file, "w", encoding="utf-8") as f:
        f.writelines(lines)

def synthesize_local(text, voice_id="local-david", rate=0, volume=100):
    """Synthesize speech using Windows System.Speech via synth.ps1."""
    voice_map = {
        "local-david": "Microsoft David Desktop",
        "local-zira": "Microsoft Zira Desktop",
        "local-hazel": "Microsoft Hazel Desktop"
    }
    system_voice = voice_map.get(voice_id, "Microsoft David Desktop")

    thread_id = threading.get_ident()
    temp_wav = os.path.join(BASE_DIR, f"_temp_speech_{os.getpid()}_{thread_id}.wav")
    ps_script = os.path.join(BASE_DIR, "synth.ps1")

    cmd = [
        "powershell", "-ExecutionPolicy", "Bypass", "-NoProfile", "-NonInteractive",
        "-File", ps_script,
        "-Text", text,
        "-OutPath", temp_wav,
        "-Voice", system_voice,
        "-Rate", str(rate),
        "-Volume", str(volume)
    ]

    try:
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30)
        if proc.returncode != 0:
            err_msg = proc.stderr.decode("utf-8", errors="ignore")
            raise RuntimeError(f"PowerShell synthesis failed: {err_msg}")
        if not os.path.isfile(temp_wav):
            raise RuntimeError("Audio file was not generated by local synthesizer.")
        with open(temp_wav, "rb") as f:
            data = f.read()
        return data
    finally:
        if os.path.isfile(temp_wav):
            try:
                os.remove(temp_wav)
            except Exception:
                pass


class ElevenNarrateHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=BASE_DIR, **kwargs)

    def end_headers(self):
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type, xi-api-key, x-elevenlabs-api-key, x-did-api-key, Authorization")
        super().end_headers()

    def do_OPTIONS(self):
        self.send_response(204)
        self.end_headers()

    def do_GET(self):
        # Serverless voices proxy endpoint
        if self.path.startswith("/.netlify/functions/voices"):
            self.handle_voices()
            return
        # Account diagnostic endpoint
        if self.path.startswith("/.netlify/functions/account") or self.path.startswith("/api/account"):
            self.handle_account_status()
            return
        # Standard static file serving
        return super().do_GET()

    def do_POST(self):
        # Serverless text-to-speech proxy endpoint
        if self.path.startswith("/.netlify/functions/tts"):
            self.handle_tts()
            return
        # Save API key to .env
        if self.path.startswith("/.netlify/functions/save-key"):
            self.handle_save_key()
            return
        # D-ID talking avatar proxy endpoint
        if self.path.startswith("/.netlify/functions/did"):
            self.handle_did()
            return
        self.send_error(404, "Endpoint not found")

    def get_api_key(self, payload=None):
        """Retrieve ElevenLabs key from request header, payload, or .env."""
        header_key = self.headers.get("xi-api-key") or self.headers.get("x-elevenlabs-api-key")
        if header_key and header_key.strip():
            return header_key.strip()
        if payload and isinstance(payload, dict):
            p_key = payload.get("apiKey") or payload.get("elevenLabsApiKey")
            if p_key and p_key.strip():
                return p_key.strip()
        env_keys = load_env_keys()
        return env_keys.get("ELEVENLABS_API_KEY", "").strip()

    def handle_account_status(self):
        """Check ElevenLabs account status and diagnose unusual activity blocks."""
        api_key = self.get_api_key()
        if not api_key or api_key == "your_elevenlabs_api_key_here":
            self.send_json_response(200, {
                "configured": False,
                "error": "No ElevenLabs API key configured in .env",
                "localSynthesizerReady": True
            })
            return

        req = urllib.request.Request("https://api.elevenlabs.io/v1/user", headers={
            "xi-api-key": api_key,
            "Accept": "application/json"
        })

        try:
            with urllib.request.urlopen(req, timeout=10) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                sub = data.get("subscription", {})
                tier = sub.get("tier", "unknown")
                char_count = sub.get("character_count", 0)
                char_limit = sub.get("character_limit", 10000)

                # Check if TTS is actually permitted or blocked by fraud detection
                tts_test_url = "https://api.elevenlabs.io/v1/text-to-speech/CwhRBWXzGAHq8TQ4Fs17"
                test_body = json.dumps({"text": "."}).encode("utf-8")
                test_req = urllib.request.Request(tts_test_url, data=test_body, headers={
                    "xi-api-key": api_key,
                    "Content-Type": "application/json"
                })
                tts_status = "active"
                tts_message = "ElevenLabs TTS is fully functional."
                try:
                    urllib.request.urlopen(test_req, timeout=10)
                except urllib.error.HTTPError as te:
                    te_body = te.read().decode("utf-8", errors="ignore")
                    try:
                        te_json = json.loads(te_body)
                        detail = te_json.get("detail", {})
                        if isinstance(detail, dict) and detail.get("status") == "detected_unusual_activity":
                            tts_status = "unusual_activity_blocked"
                            tts_message = detail.get("message", "Free tier disabled due to unusual activity detection.")
                        elif te.code == 401:
                            tts_status = "unauthorized"
                            tts_message = "Invalid ElevenLabs API key."
                        elif te.code == 402 or te.code == 429:
                            tts_status = "quota_exceeded"
                            tts_message = "Credit limit or rate limit exceeded."
                        else:
                            tts_status = f"error_{te.code}"
                            tts_message = te_body[:200]
                    except Exception:
                        tts_status = f"error_{te.code}"
                        tts_message = te_body[:200]
                except Exception as ex:
                    tts_status = "check_skipped"
                    tts_message = str(ex)

                self.send_json_response(200, {
                    "configured": True,
                    "tier": tier,
                    "characterCount": char_count,
                    "characterLimit": char_limit,
                    "ttsStatus": tts_status,
                    "ttsMessage": tts_message,
                    "localSynthesizerReady": True
                })
        except urllib.error.HTTPError as e:
            self.send_json_response(e.code, {
                "configured": False,
                "error": f"ElevenLabs API returned {e.code}: Invalid API key.",
                "localSynthesizerReady": True
            })
        except Exception as e:
            self.send_json_response(500, {
                "configured": False,
                "error": f"Failed to connect to ElevenLabs: {str(e)}",
                "localSynthesizerReady": True
            })

    def handle_save_key(self):
        """Update API key in .env file."""
        content_len = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_len).decode("utf-8")
        try:
            payload = json.loads(body)
        except Exception:
            self.send_json_response(400, {"error": "Invalid JSON payload."})
            return

        eleven_key = payload.get("elevenLabsApiKey") or payload.get("ELEVENLABS_API_KEY")
        did_key = payload.get("didApiKey") or payload.get("DID_API_KEY")

        if eleven_key:
            save_env_key("ELEVENLABS_API_KEY", eleven_key.strip())
        if did_key:
            save_env_key("DID_API_KEY", did_key.strip())

        self.send_json_response(200, {"success": True, "message": "API keys updated successfully."})

    def handle_voices(self):
        """Return combined list of ElevenLabs voices and Local System voices."""
        api_key = self.get_api_key()
        all_voices = list(LOCAL_SYSTEM_VOICES)

        if api_key and api_key != "your_elevenlabs_api_key_here":
            url = "https://api.elevenlabs.io/v1/voices"
            req = urllib.request.Request(url, headers={
                "xi-api-key": api_key,
                "Accept": "application/json"
            })
            try:
                with urllib.request.urlopen(req, timeout=10) as resp:
                    data = json.loads(resp.read().decode("utf-8"))
                    raw_voices = data.get("voices", [])
                    for v in raw_voices:
                        desc = v.get("description") or ""
                        labels = v.get("labels") or {}
                        if not desc and labels:
                            parts = [labels.get(k) for k in ["accent", "description", "use_case"] if labels.get(k)]
                            desc = " · ".join(parts) if parts else "ElevenLabs cloud voice"

                        all_voices.append({
                            "id": v.get("voice_id"),
                            "name": v.get("name"),
                            "category": v.get("category") or "ElevenLabs",
                            "gender": labels.get("gender") or "Neutral",
                            "description": desc or "ElevenLabs cloud voice",
                            "previewUrl": v.get("preview_url"),
                            "engine": "elevenlabs"
                        })
            except Exception as e:
                # Upstream error loading voices, proceed with local voices
                pass

        self.send_json_response(200, {
            "success": True,
            "voices": all_voices
        })

    def handle_tts(self):
        """Generate audio via ElevenLabs or Local System Synthesizer."""
        content_len = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_len).decode("utf-8")

        try:
            payload = json.loads(body)
        except Exception:
            self.send_json_response(400, {
                "error": "Invalid JSON payload.",
                "code": "INVALID_JSON"
            })
            return

        text = payload.get("text", "").strip()
        voice_id = payload.get("voiceId", "").strip()
        model_id = payload.get("modelId", "eleven_multilingual_v2").strip()
        settings = payload.get("voiceSettings", {})
        engine = payload.get("engine", "elevenlabs").lower()
        auto_fallback = payload.get("autoFallback", True)
        api_key = self.get_api_key(payload)

        if not text:
            self.send_json_response(400, {
                "error": "Enter some text before generating narration.",
                "code": "EMPTY_TEXT"
            })
            return

        if len(text) > 10000:
            self.send_json_response(400, {
                "error": "Script exceeds character limit.",
                "code": "TEXT_TOO_LONG"
            })
            return

        # Explicit Local System voice or Local Engine selected
        if engine == "local" or voice_id.startswith("local-"):
            try:
                # Convert rate slider (0.5 to 2.0) into PowerShell rate (-10 to 10)
                speed = float(settings.get("speed", 1.0))
                rate_val = int((speed - 1.0) * 10)
                rate_val = max(-10, min(10, rate_val))

                audio_data = synthesize_local(text, voice_id=voice_id, rate=rate_val)
                self.send_response(200)
                self.send_header("Content-Type", "audio/wav")
                self.send_header("Content-Length", str(len(audio_data)))
                self.send_header("X-Audio-Engine", "local-system")
                self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
                self.send_header("Content-Disposition", 'inline; filename="local-narration.wav"')
                self.end_headers()
                self.wfile.write(audio_data)
                return
            except Exception as e:
                self.send_json_response(500, {
                    "error": f"Local speech synthesis error: {str(e)}",
                    "code": "LOCAL_SYNTH_ERROR"
                })
                return

        # ElevenLabs Cloud Generation Flow
        if not api_key or api_key == "your_elevenlabs_api_key_here":
            if auto_fallback:
                # Fall back to local synthesis seamlessly
                try:
                    audio_data = synthesize_local(text, voice_id="local-david")
                    self.send_response(200)
                    self.send_header("Content-Type", "audio/wav")
                    self.send_header("Content-Length", str(len(audio_data)))
                    self.send_header("X-Audio-Engine", "local-fallback")
                    self.send_header("X-Fallback-Reason", "missing-api-key")
                    self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
                    self.send_header("Content-Disposition", 'inline; filename="local-narration.wav"')
                    self.end_headers()
                    self.wfile.write(audio_data)
                    return
                except Exception:
                    pass

            self.send_json_response(500, {
                "error": "Server configuration error: ELEVENLABS_API_KEY is not configured.",
                "code": "MISSING_API_KEY",
                "canFallbackLocal": True
            })
            return

        clean_settings = {
            "stability": max(0.0, min(1.0, float(settings.get("stability", 0.5)))),
            "similarity_boost": max(0.0, min(1.0, float(settings.get("similarityBoost", settings.get("similarity_boost", 0.75))))),
            "style": max(0.0, min(1.0, float(settings.get("style", 0.0)))),
            "use_speaker_boost": bool(settings.get("useSpeakerBoost", settings.get("use_speaker_boost", True)))
        }

        # If voice_id is empty or was local, use default premade ElevenLabs voice
        if not voice_id or voice_id.startswith("local-"):
            voice_id = "CwhRBWXzGAHq8TQ4Fs17" # Roger

        tts_url = f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}?output_format=mp3_44100_128"
        req_data = json.dumps({
            "text": text,
            "model_id": model_id,
            "voice_settings": clean_settings
        }).encode("utf-8")

        req = urllib.request.Request(tts_url, data=req_data, headers={
            "xi-api-key": api_key,
            "Content-Type": "application/json",
            "Accept": "audio/mpeg"
        })

        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                audio_bytes = resp.read()
                self.send_response(200)
                self.send_header("Content-Type", "audio/mpeg")
                self.send_header("Content-Length", str(len(audio_bytes)))
                self.send_header("X-Audio-Engine", "elevenlabs")
                self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
                self.send_header("Content-Disposition", 'inline; filename="eleven-narrate.mp3"')
                self.end_headers()
                self.wfile.write(audio_bytes)
        except urllib.error.HTTPError as e:
            raw_err = e.read().decode("utf-8", errors="ignore")
            try:
                err_data = json.loads(raw_err)
            except Exception:
                err_data = {}

            detail = err_data.get("detail", {})
            detail_msg = detail if isinstance(detail, str) else detail.get("message", "")
            status_tag = detail.get("status", "") if isinstance(detail, dict) else ""

            # Check if ElevenLabs detected unusual activity on Free Tier
            is_unusual_activity = (status_tag == "detected_unusual_activity" or "unusual activity" in detail_msg.lower())

            if is_unusual_activity:
                # If auto-fallback is enabled, generate via local engine immediately
                if auto_fallback:
                    try:
                        audio_data = synthesize_local(text, voice_id="local-david")
                        self.send_response(200)
                        self.send_header("Content-Type", "audio/wav")
                        self.send_header("Content-Length", str(len(audio_data)))
                        self.send_header("X-Audio-Engine", "local-fallback")
                        self.send_header("X-Fallback-Reason", "elevenlabs-unusual-activity")
                        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
                        self.send_header("Content-Disposition", 'inline; filename="local-narration.wav"')
                        self.end_headers()
                        self.wfile.write(audio_data)
                        return
                    except Exception as le:
                        pass

                self.send_json_response(401, {
                    "error": "ElevenLabs Free Tier Blocked: Unusual activity detected on your ElevenLabs account (frequent with VPNs or free tiers). Upgrade to a paid ElevenLabs plan or switch Engine to 'Local Studio Synthesizer'.",
                    "code": "ELEVENLABS_UNUSUAL_ACTIVITY",
                    "canFallbackLocal": True,
                    "detail": detail_msg
                })
                return

            user_msg = f"ElevenLabs error ({e.code}): {detail_msg}" if detail_msg else "ElevenLabs narration failed."
            self.send_json_response(e.code, {
                "error": user_msg,
                "code": "ELEVENLABS_API_ERROR",
                "canFallbackLocal": True
            })
        except Exception as e:
            if auto_fallback:
                try:
                    audio_data = synthesize_local(text, voice_id="local-david")
                    self.send_response(200)
                    self.send_header("Content-Type", "audio/wav")
                    self.send_header("Content-Length", str(len(audio_data)))
                    self.send_header("X-Audio-Engine", "local-fallback")
                    self.send_header("X-Fallback-Reason", "elevenlabs-network-error")
                    self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
                    self.send_header("Content-Disposition", 'inline; filename="local-narration.wav"')
                    self.end_headers()
                    self.wfile.write(audio_data)
                    return
                except Exception:
                    pass

            self.send_json_response(504, {
                "error": "Network timeout connecting to ElevenLabs.",
                "code": "NETWORK_TIMEOUT",
                "canFallbackLocal": True
            })

    def handle_did(self):
        """Create talking avatar video via D-ID API."""
        env_keys = load_env_keys()
        did_key = self.headers.get("x-did-api-key") or env_keys.get("DID_API_KEY", "").strip()

        if not did_key or did_key == "your_did_api_key_here":
            self.send_json_response(400, {
                "error": "D-ID API key is not configured. Please add DID_API_KEY to .env or settings.",
                "code": "MISSING_DID_KEY"
            })
            return

        content_len = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_len).decode("utf-8")
        try:
            payload = json.loads(body)
        except Exception:
            self.send_json_response(400, {"error": "Invalid JSON payload."})
            return

        url = "https://api.d-id.com/talks"
        req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={
            "Authorization": f"Basic {did_key}",
            "Content-Type": "application/json"
        })

        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                self.send_json_response(200, data)
        except urllib.error.HTTPError as e:
            raw_err = e.read().decode("utf-8", errors="ignore")
            self.send_json_response(e.code, {"error": f"D-ID API error: {raw_err}"})
        except Exception as e:
            self.send_json_response(500, {"error": f"Failed to connect to D-ID: {str(e)}"})

    def send_json_response(self, status, obj):
        data = json.dumps(obj).encode("utf-8")
        try:
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, private")
            self.end_headers()
            self.wfile.write(data)
        except (ConnectionResetError, ConnectionAbortedError, BrokenPipeError, OSError):
            pass

def main():
    keys = load_env_keys()
    api_key = keys.get("ELEVENLABS_API_KEY")
    print("=" * 65)
    print("  ElevenNarrate & D-ID Studio - Local Development Server")
    print("=" * 65)
    if api_key and api_key != "your_elevenlabs_api_key_here":
        masked_key = api_key[:4] + "..." + api_key[-4:]
        print(f" [OK] ELEVENLABS_API_KEY loaded securely ({masked_key})")
    else:
        print(" [!] NOTE: ELEVENLABS_API_KEY is not configured (Local Synthesizer active)")
    print(" [OK] Local Windows System Synthesizer: READY (David, Zira, Hazel)")
    print(f" [OK] Local Studio URL: http://localhost:{PORT}")
    print(" [OK] Press Ctrl + C to stop the server.")
    print("=" * 65)

    server = ThreadingHTTPServer(("localhost", PORT), ElevenNarrateHandler)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStudio server stopped.")
        server.server_close()

if __name__ == "__main__":
    main()
